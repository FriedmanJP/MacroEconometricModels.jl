"""
Quantile Factor Model Distributional Forecasting and Growth-at-Risk (QFM-07, #889).

Implements:
1. Multi-step quantile factor forecasting via QAR(p)/QVAR(p) dynamics on estimated
   quantile factors `F̂_t(τ)` and mapping back to panel observables in original units,
   with optional moving-block bootstrap confidence intervals and Chernozhukov,
   Fernández-Val & Galichon (2010) monotone rearrangement across quantile grids.
2. Direct h-step Growth-at-Risk (`GaR`) conditional quantile regressions and
   Adrian, Boyarchenko & Giannone (2019) Azzalini–Capitanio (2003) skewed-t density
   fitting via `Optim.LBFGS` + `Optim.NelderMead` refinement, Expected Shortfall,
   upside/downside relative entropy, quantile scores, CRPS, and out-of-sample PITs.

References:
- Adrian, T., Boyarchenko, N., & Giannone, D. (2019). Vulnerable growth.
  *American Economic Review*, 109(4), 1263–1289.
- Azzalini, A., & Capitanio, A. (2003). Distributions generated by perturbation of
  symmetry with emphasis on a multivariate skew t-distribution. *Journal of the Royal
  Statistical Society: Series B*, 65(2), 367–389.
- Chen, L., Dolado, J. J., & Gonzalo, J. (2021). Quantile factor models.
  *Econometrica*, 89(2), 875–910.
- Chernozhukov, V., Fernández-Val, I., & Galichon, A. (2010). Quantile and probability
  curves without crossing. *Econometrica*, 78(3), 1093–1125.
"""

using LinearAlgebra, Statistics, StatsAPI, Random
