"""
    GrowthAtRiskResult{T<:AbstractFloat}

Result of Adrian–Boyarchenko–Giannone (2019) direct quantile-regression Growth-at-Risk
and conditional density estimation via [`growth_at_risk`](@ref).

```math
Q_{y_{t+h}}(\\tau \\mid I_t) = \\alpha_h(\\tau) + \\beta_h(\\tau)' \\hat{F}_t(\\tau) + \\gamma_h(\\tau)' y_{t:-1:t-p+1},
\\qquad
\\mathrm{GaR}_{\\alpha, t} = \\hat{F}_{t+h \\mid t}^{-1}(\\alpha),
\\qquad
\\mathrm{ES}_{\\alpha, t} = \\frac{1}{\\alpha} \\int_0^\\alpha \\hat{F}_{t+h \\mid t}^{-1}(u)\\, du
```

where:
- ``y_{t+h}`` is the ``h``-step-ahead target variable
- ``\\hat{F}_t(\\tau)`` is the vector of estimated quantile factors at quantile level ``\\tau``
- ``y_{t:-1:t-p+1}`` are the ``p`` target lags (with `p = lags`)
- ``\\hat{F}_{t+h \\mid t}`` is the fitted conditional predictive distribution (`:skewed_t`, `:normal`, or empirical `:none`)
- ``\\mathrm{GaR}_{\\alpha, t}`` and ``\\mathrm{ES}_{\\alpha, t}`` are Growth-at-Risk and Expected Shortfall at tail probability ``\\alpha``

# Fields
- `y::Vector{T}` — full target series (length `n_obs`)
- `target_name::String` — name of the target variable
- `taus::Vector{T}` — quantile levels strictly in `(0, 1)` (length `M`)
- `horizon::Int` — forecast horizon `h`
- `lags::Int` — number of target lags included in direct quantile regressions
- `alpha::T` — tail probability level in `(0, 1)` for GaR and Expected Shortfall
- `density::Symbol` — predictive density family (`:skewed_t`, `:normal`, or `:none`)
- `rearrange::Bool` — whether Chernozhukov–Fernández-Val–Galichon (2010) rearrangement was applied
- `fitted_quantiles::Matrix{T}` — in-sample fitted conditional quantiles (`n_eff × M`)
- `actual_target::Vector{T}` — aligned in-sample realized target values `y_{t+h}` (length `n_eff`)
- `oos_quantiles::Vector{T}` — out-of-sample `T+h|T` conditional quantile forecast across `taus` (length `M`)
- `coefficients::Vector{Vector{T}}` — direct quantile regression parameter vectors per quantile (`length M`)
- `density_params::Matrix{T}` — in-sample fitted density parameters (`n_eff × 4` for `:skewed_t` `[μ, σ, α_skew, ν]`, `n_eff × 2` for `:normal` `[μ, σ]`, `0 × 0` for `:none`)
- `oos_density_params::Vector{T}` — `T+h|T` fitted density parameters (length 4, 2, or 0)
- `gar::Vector{T}` — in-sample Growth-at-Risk `GaR_α` series (length `n_eff`)
- `expected_shortfall::Vector{T}` — in-sample Expected Shortfall `ES_α` series (length `n_eff`)
- `upside_entropy::Vector{T}` — in-sample upside relative entropy above the conditional median (length `n_eff`)
- `downside_entropy::Vector{T}` — in-sample downside relative entropy below the conditional median (length `n_eff`)
- `oos_gar::T` — `T+h|T` Growth-at-Risk forecast
- `oos_expected_shortfall::T` — `T+h|T` Expected Shortfall forecast
- `oos_upside_entropy::T` — `T+h|T` upside relative entropy
- `oos_downside_entropy::T` — `T+h|T` downside relative entropy
- `quantile_score::Vector{T}` — mean in-sample check-loss quantile score per quantile level (length `M`)
- `crps::Vector{T}` — in-sample Continuous Ranked Probability Score series (length `n_eff`)
- `oos_split::Union{Int,Nothing}` — origin index where expanding-window OOS evaluation starts (or `nothing`)
- `pit::Vector{T}` — OOS Probability Integral Transforms `F_{t+h|t}(y_{t+h})` (`T[]` when `oos_split === nothing`)
- `oos_quantile_scores::Vector{T}` — mean OOS check-loss quantile score per quantile level (`T[]` when `oos_split === nothing`)
- `oos_crps::Vector{T}` — OOS CRPS series (`T[]` when `oos_split === nothing`)
- `n_obs::Int` — full sample length `T_obs`
- `n_eff::Int` — effective in-sample estimation length `T_eff`
- `manifest::Union{ReproManifest,Nothing}` — reproducibility metadata (`nothing` when `seed === nothing`)
"""
struct GrowthAtRiskResult{T<:AbstractFloat}
    y::Vector{T}
    target_name::String
    taus::Vector{T}
    horizon::Int
    lags::Int
    alpha::T
    density::Symbol
    rearrange::Bool
    fitted_quantiles::Matrix{T}
    actual_target::Vector{T}
    oos_quantiles::Vector{T}
    coefficients::Vector{Vector{T}}
    density_params::Matrix{T}
    oos_density_params::Vector{T}
    gar::Vector{T}
    expected_shortfall::Vector{T}
    upside_entropy::Vector{T}
    downside_entropy::Vector{T}
    oos_gar::T
    oos_expected_shortfall::T
    oos_upside_entropy::T
    oos_downside_entropy::T
    quantile_score::Vector{T}
    crps::Vector{T}
    oos_split::Union{Int,Nothing}
    pit::Vector{T}
    oos_quantile_scores::Vector{T}
    oos_crps::Vector{T}
    n_obs::Int
    n_eff::Int
    manifest::Union{ReproManifest,Nothing}
end

GrowthAtRiskResult{T}(
    y, target_name, taus, horizon, lags, alpha, density, rearrange,
    fitted_quantiles, actual_target, oos_quantiles, coefficients,
    density_params, oos_density_params, gar, expected_shortfall,
    upside_entropy, downside_entropy, oos_gar, oos_expected_shortfall,
    oos_upside_entropy, oos_downside_entropy, quantile_score, crps,
    oos_split, pit, oos_quantile_scores, oos_crps, n_obs, n_eff;
    manifest=nothing,
) where {T<:AbstractFloat} = GrowthAtRiskResult{T}(
    y, target_name, taus, horizon, lags, alpha, density, rearrange,
    fitted_quantiles, actual_target, oos_quantiles, coefficients,
    density_params, oos_density_params, gar, expected_shortfall,
