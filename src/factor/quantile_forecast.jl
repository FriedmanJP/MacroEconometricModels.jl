function Base.show(io::IO, r::GrowthAtRiskResult{T}) where {T}
    dens_str = r.density === :skewed_t ? "Skewed-t (Azzalini–Capitanio)" :
               r.density === :normal   ? "Normal" : "Empirical (none)"
    spec = Any[
        "Target"           r.target_name;
        "Horizon (h)"      r.horizon;
        "Target lags"      r.lags;
        "Observations (T)" r.n_obs;
        "Effective sample" r.n_eff;
        "Density"          dens_str;
        "Rearranged"       _yesno(r.rearrange);
        "Tail level (α)"   _fmt(r.alpha; digits=3)
    ]
    if r.oos_split !== nothing
        spec = vcat(spec, Any[
            "OOS split"       r.oos_split;
            "OOS evaluations" length(r.pit)
        ])
    end
    _pretty_table(io, spec;
        title = "Growth-at-Risk Forecast (h=$(r.horizon), α=$(_fmt(r.alpha; digits=3)))",
        column_labels = ["Specification", ""],
        alignment = [:l, :r],
    )

    M = length(r.taus)
    has_oos = !isempty(r.oos_quantile_scores)
    q_cols = has_oos ? 5 : 4
    q_data = Matrix{Any}(undef, M, q_cols)
    for j in 1:M
        q_data[j, 1] = _fmt(r.taus[j]; digits=3)
        q_data[j, 2] = _fmt(r.oos_quantiles[j]; digits=4)
        q_data[j, 3] = _fmt(Statistics.mean(@view(r.fitted_quantiles[:, j])); digits=4)
        q_data[j, 4] = _fmt(r.quantile_score[j]; digits=4)
        if has_oos
            q_data[j, 5] = _fmt(r.oos_quantile_scores[j]; digits=4)
        end
    end
    q_labels = has_oos ?
        ["τ", "Forecast Q(τ)", "In-Sample Mean", "Quantile Score", "OOS Q-Score"] :
        ["τ", "Forecast Q(τ)", "In-Sample Mean", "Quantile Score"]
    _pretty_table(io, q_data;
        title = "Conditional Quantile Forecasts & Pinball Scores",
        column_labels = q_labels,
        alignment = fill(:r, q_cols),
    )

    risk_rows = Vector{Vector{Any}}()
    push!(risk_rows, Any["GaR (α)", _fmt(r.oos_gar; digits=4),
                         _fmt(Statistics.mean(r.gar); digits=4),
                         _fmt(Statistics.std(r.gar); digits=4)])
    push!(risk_rows, Any["Expected Shortfall", _fmt(r.oos_expected_shortfall; digits=4),
                         _fmt(Statistics.mean(r.expected_shortfall); digits=4),
                         _fmt(Statistics.std(r.expected_shortfall); digits=4)])
    if r.density !== :none
        push!(risk_rows, Any["Downside Entropy", _fmt(r.oos_downside_entropy; digits=4),
                             _fmt(Statistics.mean(r.downside_entropy); digits=4),
                             _fmt(Statistics.std(r.downside_entropy); digits=4)])
        push!(risk_rows, Any["Upside Entropy", _fmt(r.oos_upside_entropy; digits=4),
                             _fmt(Statistics.mean(r.upside_entropy); digits=4),
                             _fmt(Statistics.std(r.upside_entropy); digits=4)])
    end
    push!(risk_rows, Any["CRPS (in-sample)", "—",
                         _fmt(Statistics.mean(r.crps); digits=4),
                         _fmt(Statistics.std(r.crps); digits=4)])
    if !isempty(r.oos_crps)
        push!(risk_rows, Any["CRPS (OOS)", "—",
                             _fmt(Statistics.mean(r.oos_crps); digits=4),
                             _fmt(Statistics.std(r.oos_crps); digits=4)])
    end
    if !isempty(r.pit)
        push!(risk_rows, Any["PIT (OOS)", "—",
                             _fmt(Statistics.mean(r.pit); digits=4),
                             _fmt(Statistics.std(r.pit); digits=4)])
    end
    risk_mat = Matrix{Any}(undef, length(risk_rows), 4)
    for (idx, row) in enumerate(risk_rows)
        risk_mat[idx, :] = row
    end
    _pretty_table(io, risk_mat;
        title = "Tail Risk, Entropy & Density Evaluation",
        column_labels = ["Metric", "T+h Forecast", "Sample Mean", "Sample SD"],
        alignment = [:l, :r, :r, :r],
    )

    if r.density !== :none && !isempty(r.oos_density_params)
        pnames = r.density === :skewed_t ?
            ["μ (location)", "σ (scale)", "α (skewness)", "ν (d.o.f.)"] :
            ["μ (location)", "σ (scale)"]
        pdata = Matrix{Any}(undef, length(pnames), 3)
        for (i, nm) in enumerate(pnames)
            pdata[i, 1] = nm
            pdata[i, 2] = _fmt(r.oos_density_params[i]; digits=4)
            pdata[i, 3] = _fmt(Statistics.mean(@view(r.density_params[:, i])); digits=4)
        end
        _pretty_table(io, pdata;
            title = "Predictive Density Parameters",
            column_labels = ["Parameter", "T+h Forecast", "Sample Mean"],
            alignment = [:l, :r, :r],
        )
    end
    _manifest_footer(io, r.manifest)
    return nothing
end

"""
    report(r::GrowthAtRiskResult; repro=false)
    report(io::IO, r::GrowthAtRiskResult; repro=false)

Print a summary of the Growth-at-Risk forecast, conditional quantiles, tail risk measures
(`GaR`, `Expected Shortfall`), upside/downside relative entropies, and density evaluation
scores from a [`GrowthAtRiskResult`](@ref). Pass `repro=true` to include the
reproducibility manifest footer.
"""
report(r::GrowthAtRiskResult; repro::Bool=false) = report(stdout, r; repro=repro)
report(io::IO, r::GrowthAtRiskResult; repro::Bool=false) =
    (show(IOContext(io, :repro => repro), r); nothing)
