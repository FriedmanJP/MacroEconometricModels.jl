function _normal_fit_quantiles(q_vals::AbstractVector{<:Real},
                               p_vals::AbstractVector{<:Real})
    z_q = Float64[Distributions.quantile(Distributions.Normal(), Float64(p)) for p in p_vals]
    qf = Float64.(q_vals)
    vz = Statistics.var(z_q)
    if vz > 1e-12
        sig = Statistics.cov(z_q, qf) / vz
        if isfinite(sig) && sig > 1e-8
            mu = Statistics.mean(qf) - sig * Statistics.mean(z_q)
            return mu, sig
        end
    end
    return Statistics.mean(qf), max(Statistics.std(qf), 1e-6)
end

@inline function _normal_es(alpha::Float64, mu::Float64, sigma::Float64)
    nd = Distributions.Normal()
    z_a = Distributions.quantile(nd, alpha)
    return mu - sigma * Distributions.pdf(nd, z_a) / alpha
end

@inline function _normal_entropy(mu::Float64, sigma::Float64, mu0::Float64, sigma0::Float64)
    base = 0.5 * (log(sigma0 / sigma) - 0.5 + (sigma^2 + (mu - mu0)^2) / (2.0 * sigma0^2))
    shift = (sigma * (mu - mu0)) / (sigma0^2 * sqrt(2.0 * pi))
    return base - shift, base + shift
end

@inline function _normal_crps(y::Float64, mu::Float64, sigma::Float64)
    z = (y - mu) / sigma
    nd = Distributions.Normal()
    return max(sigma * (z * (2.0 * Distributions.cdf(nd, z) - 1.0) +
               2.0 * Distributions.pdf(nd, z) - 1.0 / sqrt(pi)), 0.0)
end

"""Linearly interpolate sorted quantile curve `(taus_s, q_s)` at level `u ∈ (0, 1)`."""
function _empirical_quantile(taus_s::AbstractVector{T}, q_s::AbstractVector{T},
                             u::Float64) where {T<:AbstractFloat}
    M = length(taus_s)
    M == 1 && return Float64(q_s[1])
    if u <= Float64(taus_s[1])
        slope = (Float64(q_s[2]) - Float64(q_s[1])) / max(Float64(taus_s[2] - taus_s[1]), 1e-12)
        return Float64(q_s[1]) + slope * (u - Float64(taus_s[1]))
    elseif u >= Float64(taus_s[M])
        slope = (Float64(q_s[M]) - Float64(q_s[M - 1])) / max(Float64(taus_s[M] - taus_s[M - 1]), 1e-12)
        return Float64(q_s[M]) + slope * (u - Float64(taus_s[M]))
    end
    idx = searchsortedlast(taus_s, T(u))
    idx = clamp(idx, 1, M - 1)
    t1 = Float64(taus_s[idx])
    t2 = Float64(taus_s[idx + 1])
    w = (u - t1) / max(t2 - t1, 1e-12)
    return (1.0 - w) * Float64(q_s[idx]) + w * Float64(q_s[idx + 1])
end

function _empirical_es(taus_s::AbstractVector{T}, q_s::AbstractVector{T},
                       alpha::Float64) where {T<:AbstractFloat}
    M = length(taus_s)
    M == 1 && return Float64(q_s[1])
    u_prev = 0.0
    q_prev = _empirical_quantile(taus_s, q_s, 0.0)
    integral = 0.0
    @inbounds for j in 1:M
        tj = Float64(taus_s[j])
        tj <= 0.0 && continue
        if tj >= alpha
            break
        end
        qj = Float64(q_s[j])
        integral += 0.5 * (q_prev + qj) * (tj - u_prev)
        u_prev = tj
        q_prev = qj
    end
    q_alpha = _empirical_quantile(taus_s, q_s, alpha)
    integral += 0.5 * (q_prev + q_alpha) * (alpha - u_prev)
    return integral / alpha
end

function _empirical_cdf(taus_s::AbstractVector{T}, q_s::AbstractVector{T},
                        y::Float64) where {T<:AbstractFloat}
    M = length(q_s)
    M == 1 && return y < Float64(q_s[1]) ? 0.5 * Float64(taus_s[1]) : 0.5 * (1.0 + Float64(taus_s[1]))
    y <= Float64(q_s[1]) && return clamp(Float64(taus_s[1]) * 0.5, 0.0, 1.0)
    y >= Float64(q_s[M]) && return clamp(0.5 * (1.0 + Float64(taus_s[M])), 0.0, 1.0)
    idx = searchsortedlast(q_s, T(y))
    idx = clamp(idx, 1, M - 1)
    q1, q2 = Float64(q_s[idx]), Float64(q_s[idx + 1])
    t1, t2 = Float64(taus_s[idx]), Float64(taus_s[idx + 1])
    if abs(q2 - q1) <= 1e-12
        return 0.5 * (t1 + t2)
    end
    w = (y - q1) / (q2 - q1)
    return clamp((1.0 - w) * t1 + w * t2, 0.0, 1.0)
end

function _empirical_crps(taus_s::AbstractVector{T}, q_s::AbstractVector{T},
                         y::Float64) where {T<:AbstractFloat}
    M = length(taus_s)
    losses = Vector{Float64}(undef, M)
    @inbounds for j in 1:M
        u = y - Float64(q_s[j])
        tau = Float64(taus_s[j])
        losses[j] = 2.0 * u * (tau - (u < 0.0 ? 1.0 : 0.0))
    end
    M == 1 && return losses[1]
    acc = 0.0
    @inbounds for j in 1:(M - 1)
        acc += 0.5 * (losses[j] + losses[j + 1]) * (Float64(taus_s[j + 1]) - Float64(taus_s[j]))
    end
    span = Float64(taus_s[M]) - Float64(taus_s[1])
    return span > 0.0 ? acc / span : Statistics.mean(losses)
end

