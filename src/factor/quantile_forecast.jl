"""Recover per-column `(center, scale)` mapping `fit_proc` to `qfm.common_component`."""
function _qfm_recover_standardization(qfm::QuantileFactorModel{T}) where {T<:AbstractFloat}
    N = size(qfm.X, 2)
    if !qfm.standardized
        return zeros(T, N), ones(T, N)
    end
    fit_proc = qfm.factors * qfm.loadings'
    cc = qfm.common_component
    center = Vector{T}(undef, N)
    scale = Vector{T}(undef, N)
    var_floor = max(T(1e-12), eps(T))
    scale_floor = T(1e-8)

    @inbounds for i in 1:N
        fp_col = @view fit_proc[:, i]
        cc_col = @view cc[:, i]
        v_fp = T(Statistics.var(fp_col))
        if isfinite(v_fp) && v_fp > var_floor
            s_i = T(Statistics.cov(fp_col, cc_col)) / v_fp
            if isfinite(s_i) && s_i > scale_floor
                scale[i] = s_i
                center[i] = T(Statistics.mean(cc_col)) - s_i * T(Statistics.mean(fp_col))
                continue
            end
        end
        # Fallback for zero-loading columns: median/IQR scale on raw column
        _, c_fb, s_fb = _qfm_standardize(reshape(copy(@view(qfm.X[:, i])), :, 1), true)
        center[i] = T(Statistics.mean(cc_col))
        scale[i] = max(s_fb[1], scale_floor)
    end
    return center, scale
end

"""Ridge-regularized OLS fallback `(Z'Z + ridge*I) \\ (Z'y)` via `robust_inv`."""
function _qfm_ridge_solve(Z::AbstractMatrix{T}, y::AbstractVector{T},
                          ridge::T) where {T<:AbstractFloat}
    k = size(Z, 2)
    ZtZ = Matrix{T}(Z' * Z)
    @inbounds for i in 1:k
        ZtZ[i, i] += ridge
    end
    invZ = Matrix{T}(robust_inv(Symmetric(ZtZ); silent=true))
    sol = invZ * (Z' * y)
    return sol
end

"""Fit QVAR(`p`) on factor matrix `F` (`T_obs × r`) at quantile `tau` via `_qreg_ipm!`
with univariate QAR(`p`), ridge OLS, and unconditional quantile fallbacks for edge ranks/samples."""
function _qfm_qvar_fit(F::AbstractMatrix{T}, tau::T, p::Int;
                       ws::Union{Nothing,_QRegWorkspace{T}}=nothing) where {T<:AbstractFloat}
    T_obs, r = size(F)
    T_eff = T_obs - p
    k_dim = 1 + r * p
    B = zeros(T, k_dim, r)

    if T_eff < 1
        @inbounds for k in 1:r
            B[1, k] = T(Statistics.quantile(@view(F[:, k]), tau))
        end
        return B
    end

    Y_eff, Z = construct_var_matrices(F, p)
    if T_eff > k_dim + 1
        ws_use = ws === nothing ? _QRegWorkspace{T}(T_eff, k_dim) : ws
        b_k = Vector{T}(undef, k_dim)
        tol_ipm = max(T(1e-8), T(100) * eps(T))
        for k in 1:r
            yk = @view Y_eff[:, k]
            _, conv = _qreg_ipm!(b_k, Z, yk, tau, ws_use; tol=tol_ipm, maxit=60)
            if !all(isfinite, b_k) || (!conv && sum(abs, b_k) > T(1e6))
                b_k .= _qfm_ridge_solve(Z, yk, T(1e-3))
                if !all(isfinite, b_k)
                    fill!(b_k, zero(T))
                    b_k[1] = T(Statistics.quantile(@view(F[:, k]), tau))
                end
            end
            B[:, k] .= b_k
        end
    elseif T_eff > 1 + p + 1
        # Edge sample size: univariate QAR(p) per factor column
        k_uni = 1 + p
        ws_uni = _QRegWorkspace{T}(T_eff, k_uni)
        Z_uni = Matrix{T}(undef, T_eff, k_uni)
        Z_uni[:, 1] .= one(T)
        b_uni = Vector{T}(undef, k_uni)
        tol_ipm = max(T(1e-8), T(100) * eps(T))
        for k in 1:r
            for lag in 1:p
                Z_uni[:, 1 + lag] .= @view F[(p + 1 - lag):(T_obs - lag), k]
            end
            yk = @view Y_eff[:, k]
            _qreg_ipm!(b_uni, Z_uni, yk, tau, ws_uni; tol=tol_ipm, maxit=60)
            if all(isfinite, b_uni)
                B[1, k] = b_uni[1]
                for lag in 1:p
                    B[1 + (lag - 1) * r + k, k] = b_uni[1 + lag]
                end
            else
                B[1, k] = T(Statistics.quantile(@view(F[:, k]), tau))
            end
        end
    elseif T_eff >= 2
        for k in 1:r
            b_k = _qfm_ridge_solve(Z, @view(Y_eff[:, k]), T(1e-2))
            if all(isfinite, b_k)
                B[:, k] .= b_k
            else
                B[1, k] = T(Statistics.quantile(@view(F[:, k]), tau))
            end
        end
    else
        @inbounds for k in 1:r
            B[1, k] = T(Statistics.quantile(@view(F[:, k]), tau))
        end
    end
    return B
end

"""Iterate QVAR(`p`) point forecast `h` steps ahead from terminal factor history `F`."""
function _qfm_qvar_predict(F::AbstractMatrix{T}, B::AbstractMatrix{T},
                           h::Int, p::Int) where {T<:AbstractFloat}
    T_obs, r = size(F)
    F_fc = Matrix{T}(undef, h, r)
    z_step = Vector{T}(undef, 1 + r * p)
    z_step[1] = one(T)

    @inbounds for step in 1:h
        for lag in 1:p
            offset = 1 + (lag - 1) * r
            src_step = step - lag
            if src_step >= 1
                for k in 1:r
                    z_step[offset + k] = F_fc[src_step, k]
                end
            else
                src_t = T_obs + src_step
                for k in 1:r
                    z_step[offset + k] = F[src_t, k]
                end
            end
        end
        for k in 1:r
            acc = zero(T)
            for j in 1:(1 + r * p)
                acc += z_step[j] * B[j, k]
            end
            F_fc[step, k] = acc
        end
    end
    return F_fc
end

"""Moving-block bootstrap confidence intervals for QFM factor and observable forecasts."""
function _qfm_forecast_block_boot(F::Matrix{T}, loadings::Matrix{T},
                                  center::Vector{T}, scale::Vector{T},
                                  standardized::Bool, tau::T, p::Int, h::Int,
                                  n_boot::Int, conf_level::T,
                                  rng_use::AbstractRNG) where {T<:AbstractFloat}
    T_obs, r = size(F)
    N = size(loadings, 1)
    T_eff = T_obs - p
    k_dim = 1 + r * p

    ell = clamp(ceil(Int, cbrt(max(T_eff, 1))), 1, max(T_eff, 1))
    boot_seeds = rand(rng_use, UInt64, n_boot)

    F_boot = Array{T,3}(undef, n_boot, h, r)
    X_boot = Array{T,3}(undef, n_boot, h, N)

    Y_eff, Z = construct_var_matrices(F, p)
    Z_b = Matrix{T}(undef, T_eff, k_dim)
    Y_b = Matrix{T}(undef, T_eff, r)
    idx = Vector{Int}(undef, T_eff)

    use_joint = T_eff > k_dim + 1
    ws_b = use_joint ? _QRegWorkspace{T}(T_eff, k_dim) : nothing
    b_k = Vector{T}(undef, k_dim)
    B_b = zeros(T, k_dim, r)
    tol_ipm = max(T(1e-7), T(100) * eps(T))

    for b in 1:n_boot
        local_rng = Random.Xoshiro(boot_seeds[b])
        _qfm_grid_block_indices!(idx, local_rng, T_eff, ell)
        @inbounds for j in 1:k_dim, t in 1:T_eff
            Z_b[t, j] = Z[idx[t], j]
        end
        @inbounds for k in 1:r, t in 1:T_eff
            Y_b[t, k] = Y_eff[idx[t], k]
        end

        fill!(B_b, zero(T))
        if use_joint
            for k in 1:r
                yk = @view Y_b[:, k]
                _, conv = _qreg_ipm!(b_k, Z_b, yk, tau, ws_b; tol=tol_ipm, maxit=50)
                if !all(isfinite, b_k) || (!conv && sum(abs, b_k) > T(1e6))
                    b_k .= _qfm_ridge_solve(Z_b, yk, T(1e-2))
                    if !all(isfinite, b_k)
                        fill!(b_k, zero(T))
                        b_k[1] = T(Statistics.quantile(@view(F[:, k]), tau))
                    end
                end
                B_b[:, k] .= b_k
            end
        else
            for k in 1:r
                b_sol = _qfm_ridge_solve(Z_b, @view(Y_b[:, k]), T(1e-2))
                if all(isfinite, b_sol)
                    B_b[:, k] .= b_sol
                else
                    B_b[1, k] = T(Statistics.quantile(@view(F[:, k]), tau))
                end
            end
        end

        F_fc_b = _qfm_qvar_predict(F, B_b, h, p)
        X_fc_b = F_fc_b * loadings'
        if standardized
            X_fc_b .= X_fc_b .* scale' .+ center'
        end
        @inbounds for step in 1:h
            for k in 1:r
                F_boot[b, step, k] = F_fc_b[step, k]
            end
            for i in 1:N
                X_boot[b, step, i] = X_fc_b[step, i]
            end
        end
    end

    alpha_lo = (one(T) - conf_level) / T(2)
    alpha_hi = one(T) - alpha_lo
    F_lo = T[Statistics.quantile(@view(F_boot[:, step, k]), alpha_lo) for step in 1:h, k in 1:r]
    F_hi = T[Statistics.quantile(@view(F_boot[:, step, k]), alpha_hi) for step in 1:h, k in 1:r]
    X_lo = T[Statistics.quantile(@view(X_boot[:, step, i]), alpha_lo) for step in 1:h, i in 1:N]
    X_hi = T[Statistics.quantile(@view(X_boot[:, step, i]), alpha_hi) for step in 1:h, i in 1:N]
    F_se = T[Statistics.std(@view(F_boot[:, step, k])) for step in 1:h, k in 1:r]
    X_se = T[Statistics.std(@view(X_boot[:, step, i])) for step in 1:h, i in 1:N]

    return F_lo, F_hi, X_lo, X_hi, F_se, X_se
end

"""
    forecast(qfm::QuantileFactorModel{T}, h::Int; p::Int=1, ci_method::Symbol=:none,
             conf_level::Real=DEFAULT_CI_MACRO, n_boot::Int=299, rng::AbstractRNG=Random.default_rng(),
             seed::Union{Integer,Nothing}=nothing) -> FactorForecast{T}

Forecast quantile factors and panel observables `h` steps ahead from an estimated
[`QuantileFactorModel`](@ref) via QAR(`p`)/QVAR(`p`) quantile autoregression at `qfm.tau`.

```math
\\hat{f}_{t+1 \\mid t}(\\tau) = \\hat{c}(\\tau) + \\sum_{\\ell=1}^{p} \\hat{A}_\\ell(\\tau)\\, \\hat{f}_{t+1-\\ell}(\\tau),
\\qquad
\\hat{Q}_{\\tau}(X_{T+h} \\mid I_T) = \\mu_X + \\sigma_X \\odot \\left(\\hat{\\Lambda}(\\tau)\\, \\hat{f}_{T+h \\mid T}(\\tau)\\right)
```

where:
- ``\\hat{f}_t(\\tau) \\in \\mathbb{R}^r`` are the normalized quantile factors from `qfm`
- ``\\hat{c}(\\tau), \\hat{A}_\\ell(\\tau)`` are the QVAR(`p`) intercept and lag matrices estimated via interior-point check-loss minimization at quantile ``\\tau``
- ``\\hat{\\Lambda}(\\tau) \\in \\mathbb{R}^{N \\times r}`` is the quantile loading matrix
- ``\\mu_X, \\sigma_X`` are the column centering and scaling vectors when `qfm.standardized == true` (``\\mu_X = 0, \\sigma_X = 1`` otherwise)

# Arguments
- `qfm::QuantileFactorModel{T}` — fitted single-quantile factor model
- `h::Int` — positive forecast horizon

# Keyword Arguments
- `p::Int = 1` — QAR/QVAR lag order (`1 ≤ p < T_obs`)
- `ci_method::Symbol = :none` — confidence interval method (`:none` or `:bootstrap` moving-block bootstrap)
- `conf_level::Real = 0.68` — confidence level in `(0, 1)` when `ci_method = :bootstrap` (`DEFAULT_CI_MACRO`)
- `n_boot::Int = 299` — number of moving-block bootstrap replications (`>= 2` when `ci_method = :bootstrap`)
- `rng::AbstractRNG = Random.default_rng()` — RNG for bootstrap resampling
- `seed::Union{Integer,Nothing} = nothing` — integer seed overriding `rng` via `Xoshiro(seed)`

# Returns
A [`FactorForecast`](@ref) containing `h × r` factor forecasts and `h × N` observable
forecasts in raw panel units (with zero bounds/SEs when `ci_method == :none`).
"""
function forecast(qfm::QuantileFactorModel{T}, h::Int;
                  p::Int=1,
                  ci_method::Symbol=:none,
                  conf_level::Real=DEFAULT_CI_MACRO,
                  n_boot::Int=299,
                  rng::AbstractRNG=Random.default_rng(),
                  seed::Union{Integer,Nothing}=nothing) where {T<:AbstractFloat}
    h >= 1 || throw(ArgumentError("forecast horizon h must be >= 1, got $h"))
    p >= 1 || throw(ArgumentError("QAR/QVAR lag order p must be >= 1, got $p"))
    validate_option(ci_method, "ci_method", (:none, :bootstrap))
    conf_T = T(_validate_conf_level(conf_level))
    if ci_method === :bootstrap
        n_boot >= 2 || throw(ArgumentError("n_boot must be >= 2 when ci_method=:bootstrap, got $n_boot"))
    else
        n_boot >= 1 || throw(ArgumentError("n_boot must be >= 1, got $n_boot"))
    end

    T_obs, r = size(qfm.factors)
    N = size(qfm.X, 2)
    T_obs > p || throw(ArgumentError("Not enough observations (T=$T_obs) for lag order p=$p"))

    rng_use = _resolve_repro_rng(rng, seed)
    B = _qfm_qvar_fit(qfm.factors, qfm.tau, p)
    F_fc = _qfm_qvar_predict(qfm.factors, B, h, p)
    X_fc = F_fc * qfm.loadings'

    center, scale = _qfm_recover_standardization(qfm)
    if qfm.standardized
        X_fc .= X_fc .* scale' .+ center'
    end

    if ci_method === :none
        return _build_factor_forecast(
            F_fc, X_fc,
            zeros(T, h, r), zeros(T, h, r),
            zeros(T, h, N), zeros(T, h, N),
            zeros(T, h, r), zeros(T, h, N),
            h, conf_T, :none,
        )
    end

    F_lo, F_hi, X_lo, X_hi, F_se, X_se = _qfm_forecast_block_boot(
        qfm.factors, qfm.loadings, center, scale, qfm.standardized,
        qfm.tau, p, h, n_boot, conf_T, rng_use,
    )
    return _build_factor_forecast(F_fc, X_fc, F_lo, F_hi, X_lo, X_hi, F_se, X_se, h, conf_T, :bootstrap)
end

"""
    forecast(grid::QuantileFactorGrid{T}, h::Int; p::Int=1, rearrange::Bool=true,
             kwargs...) -> Vector{FactorForecast{T}}

Forecast all quantile levels in a [`QuantileFactorGrid`](@ref) `h` steps ahead via QAR(`p`)/QVAR(`p`),
optionally applying Chernozhukov–Fernández-Val–Galichon (2010) monotone rearrangement
(`sort!` across `τ` at every horizon–variable cell) so conditional quantile forecasts do not cross.

```math
\\hat{Q}^{\\mathrm{rearr}}_{\\tau_j}(X_{T+h, i} \\mid I_T) = \\mathrm{sort}_j\\!\\left(\\{\\hat{Q}_{\\tau_m}(X_{T+h, i} \\mid I_T)\\}_{m=1}^M\\right)_j
```

where:
- ``M`` is the number of quantile levels in `grid`
- ``\\tau_1 \\le \\dots \\le \\tau_M`` are the sorted quantile levels
- ``\\hat{Q}_{\\tau_m}(X_{T+h, i} \\mid I_T)`` is the un-rearranged ``h``-step forecast for observable ``i`` at quantile ``\\tau_m``

# Arguments
- `grid::QuantileFactorGrid{T}` — multi-quantile factor model grid
- `h::Int` — positive forecast horizon

# Keyword Arguments
- `p::Int = 1` — QAR/QVAR lag order passed to single-quantile `forecast`
- `rearrange::Bool = true` — sort observable quantile forecasts across `τ` at each `(horizon, variable)` cell
- `kwargs...` — forwarded to [`forecast`](@ref) for each quantile model (e.g., `ci_method`, `conf_level`, `n_boot`, `rng`, `seed`)

# Returns
A `Vector{FactorForecast{T}}` aligned with `grid.models`.
"""
function forecast(grid::QuantileFactorGrid{T}, h::Int;
                  p::Int=1,
                  rearrange::Bool=true,
                  kwargs...) where {T<:AbstractFloat}
    isempty(grid.models) && throw(ArgumentError("QuantileFactorGrid must not be empty"))
    h >= 1 || throw(ArgumentError("forecast horizon h must be >= 1, got $h"))
    p >= 1 || throw(ArgumentError("QAR/QVAR lag order p must be >= 1, got $p"))

    M = length(grid.models)
    kw_dict = Dict{Symbol,Any}(pairs(kwargs))
    seed_kw = pop!(kw_dict, :seed, nothing)
    rng_kw = pop!(kw_dict, :rng, Random.default_rng())
    rng_use = _resolve_repro_rng(rng_kw, seed_kw)
    slot_seeds = rand(rng_use, UInt64, M)
    fwd_kw = (; kw_dict...)

    fcs = Vector{FactorForecast{T}}(undef, M)
    for j in 1:M
        fcs[j] = forecast(grid.models[j], h; p=p, fwd_kw...,
                          rng=Random.Xoshiro(slot_seeds[j]), seed=nothing)
    end

    if rearrange && M > 1
        perm = sortperm(grid.taus)
        N = size(fcs[1].observables, 2)
        buf = Vector{T}(undef, M)
        has_ci = fcs[1].ci_method !== :none
        buf_lo = has_ci ? Vector{T}(undef, M) : T[]
        buf_hi = has_ci ? Vector{T}(undef, M) : T[]
        @inbounds for hh in 1:h, i in 1:N
            for j in 1:M
                buf[j] = fcs[perm[j]].observables[hh, i]
            end
            sort!(buf)
            for j in 1:M
                fcs[perm[j]].observables[hh, i] = buf[j]
            end
            if has_ci
                for j in 1:M
                    buf_lo[j] = fcs[perm[j]].observables_lower[hh, i]
                    buf_hi[j] = fcs[perm[j]].observables_upper[hh, i]
                end
                sort!(buf_lo)
                sort!(buf_hi)
                for j in 1:M
                    fcs[perm[j]].observables_lower[hh, i] = buf_lo[j]
                    fcs[perm[j]].observables_upper[hh, i] = buf_hi[j]
                end
            end
        end
    end
    return fcs
end

# =============================================================================
# Azzalini–Capitanio (2003) Skewed-t Distribution & Quadrature Suite
# =============================================================================

@inline function _skewt_log_c(nu::Float64)
    return SpecialFunctions.loggamma(0.5 * (nu + 1.0)) -
           SpecialFunctions.loggamma(0.5 * nu) -
           0.5 * log(nu * pi)
end

@inline function _skewt_std_logpdf_c(z::Float64, alpha::Float64, nu::Float64, log_c_nu::Float64)
    log_t = log_c_nu - 0.5 * (nu + 1.0) * log1p((z * z) / nu)
    w = alpha * z * sqrt((nu + 1.0) / (nu + z * z))
    t_cdf = max(Distributions.cdf(Distributions.TDist(nu + 1.0), w), 1e-300)
    return log(2.0) + log_t + log(t_cdf)
end

@inline function _skewt_std_pdf_c(z::Float64, alpha::Float64, nu::Float64, log_c_nu::Float64)
    t_val = exp(log_c_nu - 0.5 * (nu + 1.0) * log1p((z * z) / nu))
    w = alpha * z * sqrt((nu + 1.0) / (nu + z * z))
    return 2.0 * t_val * Distributions.cdf(Distributions.TDist(nu + 1.0), w)
end

function _skewt_pdf(y::Real, mu::Real, sigma::Real, alpha::Real, nu::Real)
    sig = Float64(sigma)
    sig > 0.0 || throw(ArgumentError("sigma must be positive, got $sigma"))
    nu_f = Float64(nu)
    nu_f > 0.0 || throw(ArgumentError("nu must be positive, got $nu"))
    z = (Float64(y) - Float64(mu)) / sig
    return _skewt_std_pdf_c(z, Float64(alpha), nu_f, _skewt_log_c(nu_f)) / sig
end

function _skewt_logpdf(y::Real, mu::Real, sigma::Real, alpha::Real, nu::Real)
    sig = Float64(sigma)
    sig > 0.0 || throw(ArgumentError("sigma must be positive, got $sigma"))
    nu_f = Float64(nu)
    nu_f > 0.0 || throw(ArgumentError("nu must be positive, got $nu"))
    z = (Float64(y) - Float64(mu)) / sig
    return _skewt_std_logpdf_c(z, Float64(alpha), nu_f, _skewt_log_c(nu_f)) - log(sig)
end

"""Tail integral ∫_{-∞}^{z_hi} f_std(u; α, ν) du for `z_hi < 0` via `w = s^3` with
`s = (|z_hi| / |u|)^{ν/3} ∈ (0, 1]` eliminating both the infinite tail and the endpoint
derivative singularity."""
function _skewt_tail_cdf(z_hi::Float64, alpha::Float64, nu::Float64, log_c_nu::Float64,
                         nodes::Vector{Float64}, weights::Vector{Float64})
    M_cut = -z_hi
    log_pref = log(6.0) + log_c_nu + 0.5 * (nu + 1.0) * log(nu) - nu * log(M_cut) - log(nu)
    td = Distributions.TDist(nu + 1.0)
    three_inv_nu = 3.0 / nu
    six_inv_nu = 6.0 / nu
    nu_over_M2 = nu / (M_cut * M_cut)
    half_np1 = 0.5 * (nu + 1.0)
    sqrt_np1 = sqrt(nu + 1.0)
    return _gl_integrate(0.0, 1.0, nodes, weights) do s
        s <= 0.0 && return 0.0
        u = -M_cut * s^(-three_inv_nu)
        log_k = log_pref - half_np1 * log1p(nu_over_M2 * s^six_inv_nu)
        arg = alpha * (-sqrt_np1) / sqrt(1.0 + nu / (u * u))
        (s * s) * exp(log_k) * Distributions.cdf(td, arg)
    end
end

"""Piecewise Gauss–Legendre integral of `f_std(u; α, ν)` over bounded `[a, b]`."""
function _skewt_core_cdf(a::Float64, b::Float64, alpha::Float64, nu::Float64,
                         log_c_nu::Float64, nodes::Vector{Float64}, weights::Vector{Float64})
    b <= a && return 0.0
    s_sk = abs(alpha) > 2.0 ? 2.5 / abs(alpha) : Inf
    total = 0.0
    cur = a
    for bp in (-16.0, -8.0, -2.5, -s_sk, 0.0, s_sk, 2.5, 8.0, 16.0)
        if bp > cur && bp < b
            total += _gl_integrate(u -> _skewt_std_pdf_c(u, alpha, nu, log_c_nu),
                                   cur, bp, nodes, weights)
            cur = bp
        end
    end
    if cur < b
        total += _gl_integrate(u -> _skewt_std_pdf_c(u, alpha, nu, log_c_nu),
                               cur, b, nodes, weights)
    end
    return total
end

function _skewt_std_cdf(z::Float64, alpha::Float64, nu::Float64; fast_mode::Bool=false)
    isnan(z) && return NaN
    z == -Inf && return 0.0
    z == Inf && return 1.0
    if abs(alpha) <= 1e-14
        return Distributions.cdf(Distributions.TDist(nu), z)
    end
    if z == 0.0
        return 0.5 - atan(alpha) / pi
    end
    if z > 2.0
        return clamp(1.0 - _skewt_std_cdf(-z, -alpha, nu; fast_mode=fast_mode), 0.0, 1.0)
    end
    log_c_nu = _skewt_log_c(nu)
    nodes = fast_mode ? _GL_NODES_8 : _GL_NODES_16
    weights = fast_mode ? _GL_WEIGHTS_8 : _GL_WEIGHTS_16
    f0 = 0.5 - atan(alpha) / pi
    if z > 0.0
        core = _skewt_core_cdf(0.0, z, alpha, nu, log_c_nu, nodes, weights)
        return clamp(f0 + core, 0.0, 1.0)
    end
    # Fast exact-anchor path from F(0) = 0.5 - atan(alpha)/pi avoids tail integration for moderate z
    if -5.0 <= z && -5.0 <= alpha <= 3.5
        core = _skewt_core_cdf(z, 0.0, alpha, nu, log_c_nu, nodes, weights)
        return clamp(f0 - core, 0.0, 1.0)
    end
    M_cut = fast_mode ? 18.0 : 24.0
    if z <= -M_cut
        return clamp(_skewt_tail_cdf(z, alpha, nu, log_c_nu, nodes, weights), 0.0, 1.0)
    end
    tail = (nu > 30.0 && log_c_nu - 0.5 * (nu + 1.0) * log1p(M_cut * M_cut / nu) < -36.0) ?
           0.0 : _skewt_tail_cdf(-M_cut, alpha, nu, log_c_nu, nodes, weights)
    core = _skewt_core_cdf(-M_cut, z, alpha, nu, log_c_nu, nodes, weights)
    return clamp(tail + core, 0.0, 1.0)
end

function _skewt_cdf(y::Real, mu::Real, sigma::Real, alpha::Real, nu::Real; fast_mode::Bool=false)
    sig = Float64(sigma)
    sig > 0.0 || throw(ArgumentError("sigma must be positive, got $sigma"))
    nu_f = Float64(nu)
    nu_f > 0.0 || throw(ArgumentError("nu must be positive, got $nu"))
    z = (Float64(y) - Float64(mu)) / sig
    return _skewt_std_cdf(z, Float64(alpha), nu_f; fast_mode=fast_mode)
end

"""Incremental CDF update `F(z_to) = F(z_from) + ∫_{z_from}^{z_to} f_std(u) du` over bounded step."""
@inline function _skewt_cdf_step(z_from::Float64, f_from::Float64, z_to::Float64,
                                 alpha::Float64, nu::Float64, log_c_nu::Float64;
                                 fast_mode::Bool=false)
    z_to == z_from && return f_from
    if z_to < -24.0 || z_to > 24.0 || z_from < -24.0 || z_from > 24.0
        return _skewt_std_cdf(z_to, alpha, nu; fast_mode=fast_mode)
    end
    dz = abs(z_to - z_from)
    crosses_zero = (z_from < 0.0 && z_to > 0.0) || (z_to < 0.0 && z_from > 0.0)
    use_8 = fast_mode || (dz <= 0.5 && !crosses_zero)
    nodes = use_8 ? _GL_NODES_8 : _GL_NODES_16
    weights = use_8 ? _GL_WEIGHTS_8 : _GL_WEIGHTS_16
    val = if z_to > z_from
        if dz <= 2.5 && !crosses_zero
            f_from + _gl_integrate(u -> _skewt_std_pdf_c(u, alpha, nu, log_c_nu),
                                   z_from, z_to, nodes, weights)
        else
            f_from + _skewt_core_cdf(z_from, z_to, alpha, nu, log_c_nu, nodes, weights)
        end
    else
        if dz <= 2.5 && !crosses_zero
            f_from - _gl_integrate(u -> _skewt_std_pdf_c(u, alpha, nu, log_c_nu),
                                   z_to, z_from, nodes, weights)
        else
            f_from - _skewt_core_cdf(z_to, z_from, alpha, nu, log_c_nu, nodes, weights)
        end
    end
    return clamp(val, 0.0, 1.0)
end

"""Safeguarded Newton-bisection inverse of standardized skewed-t CDF using incremental updates."""
function _skewt_std_quantile(p::Float64, alpha::Float64, nu::Float64;
                              x0::Float64=NaN, z_ref::Float64=NaN, f_ref::Float64=NaN,
                              tol_q::Float64=1e-12, fast_mode::Bool=false)
    (0.0 < p < 1.0) || throw(ArgumentError("quantile level p must be in (0, 1), got $p"))
    if abs(alpha) <= 1e-14
        return Distributions.quantile(Distributions.TDist(nu), p)
    end
    log_c_nu = _skewt_log_c(nu)
    has_ref = isfinite(z_ref) && isfinite(f_ref)

    z = isfinite(x0) ? clamp(x0, -100.0, 100.0) :
        clamp(Distributions.quantile(Distributions.TDist(nu), p), -50.0, 50.0)
    fz = has_ref ? _skewt_cdf_step(z_ref, f_ref, z, alpha, nu, log_c_nu; fast_mode=fast_mode) :
                   _skewt_std_cdf(z, alpha, nu; fast_mode=fast_mode)

    # Bracket [lo, hi] with F(lo) <= p <= F(hi)
    lo = z
    hi = z
    flo = fz
    fhi = fz
    step = 1.0
    if fz < p
        for _ in 1:40
            hi = lo + step
            fhi = _skewt_cdf_step(lo, flo, hi, alpha, nu, log_c_nu; fast_mode=fast_mode)
            if fhi >= p
                break
            end
            lo = hi
            flo = fhi
            step *= 2.0
        end
    else
        for _ in 1:40
            lo = hi - step
            flo = _skewt_cdf_step(hi, fhi, lo, alpha, nu, log_c_nu; fast_mode=fast_mode)
            if flo <= p
                break
            end
            hi = lo
            fhi = flo
            step *= 2.0
        end
    end

    if abs(flo - p) <= tol_q
        return lo
    elseif abs(fhi - p) <= tol_q
        return hi
    end

    # Start interior iterate at secant interpolation inside [lo, hi]
    denom_f = fhi - flo
    z_cur = denom_f > 1e-15 ? lo + (p - flo) * (hi - lo) / denom_f : 0.5 * (lo + hi)
    if !(lo < z_cur < hi)
        z_cur = 0.5 * (lo + hi)
    end
    f_cur = _skewt_cdf_step(lo, flo, z_cur, alpha, nu, log_c_nu; fast_mode=fast_mode)

    for _ in 1:40
        err = f_cur - p
        if abs(err) <= tol_q || (hi - lo) <= tol_q * (1.0 + abs(z_cur))
            return z_cur
        end
        if err < 0.0
            lo = z_cur
            flo = f_cur
        else
            hi = z_cur
            fhi = f_cur
        end
        pdf_val = _skewt_std_pdf_c(z_cur, alpha, nu, log_c_nu)
        z_new = pdf_val > 1e-30 ? z_cur - err / pdf_val : 0.5 * (lo + hi)
        if !(lo < z_new < hi)
            z_new = 0.5 * (lo + hi)
        end
        f_cur = _skewt_cdf_step(z_cur, f_cur, z_new, alpha, nu, log_c_nu; fast_mode=fast_mode)
        z_cur = z_new
    end
    return z_cur
end

function _skewt_quantile(p::Real, mu::Real, sigma::Real, alpha::Real, nu::Real)
    sig = Float64(sigma)
    sig > 0.0 || throw(ArgumentError("sigma must be positive, got $sigma"))
    nu_f = Float64(nu)
    nu_f > 0.0 || throw(ArgumentError("nu must be positive, got $nu"))
    return Float64(mu) + sig * _skewt_std_quantile(Float64(p), Float64(alpha), nu_f)
end

"""Tail moment ∫_{-∞}^{z_hi} u f_std(u; α, ν) du for `z_hi < 0` and `ν > 1.05` via
`v = s^3` with `s = (|z_hi| / |u|)^{(ν - 1)/3} ∈ (0, 1]`."""
function _skewt_tail_moment(z_hi::Float64, alpha::Float64, nu::Float64, log_c_nu::Float64,
                            nodes::Vector{Float64}, weights::Vector{Float64})
    M_cut = -z_hi
    nm1 = nu - 1.0
    log_pref = log(6.0) + log_c_nu + 0.5 * (nu + 1.0) * log(nu) - nm1 * log(M_cut) - log(nm1)
    td = Distributions.TDist(nu + 1.0)
    three_inv_nm1 = 3.0 / nm1
    six_inv_nm1 = 6.0 / nm1
    nu_over_M2 = nu / (M_cut * M_cut)
    half_np1 = 0.5 * (nu + 1.0)
    sqrt_np1 = sqrt(nu + 1.0)
    return -_gl_integrate(0.0, 1.0, nodes, weights) do s
        s <= 0.0 && return 0.0
        u = -M_cut * s^(-three_inv_nm1)
        log_k = log_pref - half_np1 * log1p(nu_over_M2 * s^six_inv_nm1)
        arg = alpha * (-sqrt_np1) / sqrt(1.0 + nu / (u * u))
        (s * s) * exp(log_k) * Distributions.cdf(td, arg)
    end
end

"""Expected Shortfall `ES_α = (1/α) ∫_{-∞}^{Q(α)} y f(y) dy = (1/α) ∫_0^α Q(u) du`."""
function _skewt_es(alpha_prob::Float64, mu::Float64, sigma::Float64,
                   alpha_skew::Float64, nu::Float64; z_alpha::Float64=NaN, fast_mode::Bool=false)
    z_a = isfinite(z_alpha) ? z_alpha : _skewt_std_quantile(alpha_prob, alpha_skew, nu; fast_mode=fast_mode)
    log_c_nu = _skewt_log_c(nu)
    nodes = fast_mode ? _GL_NODES_8 : _GL_NODES_16
    weights = fast_mode ? _GL_WEIGHTS_8 : _GL_WEIGHTS_16
    M_cut = fast_mode ? 16.0 : 24.0

    # Integrate ∫_{-∞}^{z_a} u f_std(u) du
    moment_std = if z_a <= -M_cut
        _skewt_tail_moment(z_a, alpha_skew, nu, log_c_nu, nodes, weights)
    else
        tail = (nu > 30.0 && log_c_nu - 0.5 * (nu + 1.0) * log1p(M_cut * M_cut / nu) < -36.0) ?
               0.0 : _skewt_tail_moment(-M_cut, alpha_skew, nu, log_c_nu, nodes, weights)
        s_sk = abs(alpha_skew) > 2.0 ? 2.5 / abs(alpha_skew) : Inf
        cur = -M_cut
        core = 0.0
        for bp in (-8.0, -2.5, -s_sk, 0.0, s_sk, 2.5, 8.0)
            if bp > cur && bp < z_a
                core += _gl_integrate(u -> u * _skewt_std_pdf_c(u, alpha_skew, nu, log_c_nu),
                                      cur, bp, nodes, weights)
                cur = bp
            end
        end
        if cur < z_a
            core += _gl_integrate(u -> u * _skewt_std_pdf_c(u, alpha_skew, nu, log_c_nu),
                                  cur, z_a, nodes, weights)
        end
        tail + core
    end
    return mu + sigma * (moment_std / alpha_prob)
end

"""Compute ABG (2019) downside and upside relative entropies `(L, U)` splitting at conditional median."""
function _skewt_entropy(mu::Float64, sigma::Float64, alpha::Float64, nu::Float64,
                        mu0::Float64, sigma0::Float64, alpha0::Float64, nu0::Float64;
                        fast_mode::Bool=false)
    z_med = _skewt_std_quantile(0.5, alpha, nu; tol_q=(fast_mode ? 1e-6 : 1e-8), fast_mode=fast_mode)
    log_c = _skewt_log_c(nu)
    log_c0 = _skewt_log_c(nu0)
    log_sig = log(sigma)
    log_sig0 = log(sigma0)
    nodes = fast_mode ? _GL_NODES_8 : _GL_NODES_16
    weights = fast_mode ? _GL_WEIGHTS_8 : _GL_WEIGHTS_16
    M_cut = fast_mode ? 10.0 : 12.0

    @inline function _kl_integrand(u::Float64)
        lp_f = _skewt_std_logpdf_c(u, alpha, nu, log_c)
        f_u = exp(lp_f)
        f_u <= 1e-300 && return 0.0
        z0 = (mu + sigma * u - mu0) / sigma0
        lp_g = _skewt_std_logpdf_c(z0, alpha0, nu0, log_c0) - log_sig0
        return f_u * ((lp_f - log_sig) - lp_g)
    end

    # Tail integrals via w = (M_cut / |u|)^nu on (0, 1]
    @inline function _kl_tail(z_bound::Float64, is_left::Bool)
        Mc = abs(z_bound)
        inv_nu = 1.0 / nu
        two_inv_nu = 2.0 * inv_nu
        nu_over_M2 = nu / (Mc * Mc)
        half_np1 = 0.5 * (nu + 1.0)
        sqrt_np1 = sqrt(nu + 1.0)
        log_pref = log(2.0) + log_c + 0.5 * (nu + 1.0) * log(nu) - nu * log(Mc) - log(nu)
        td = Distributions.TDist(nu + 1.0)
        return _gl_integrate(0.0, 1.0, nodes, weights) do w
            w <= 0.0 && return 0.0
            u = is_left ? -Mc * w^(-inv_nu) : Mc * w^(-inv_nu)
            log_jac_f = log_pref - half_np1 * log1p(nu_over_M2 * w^two_inv_nu)
            arg = alpha * (is_left ? -sqrt_np1 : sqrt_np1) / sqrt(1.0 + nu / (u * u))
            t_cdf = max(Distributions.cdf(td, arg), 1e-300)
            jac_f = exp(log_jac_f) * t_cdf
            lp_f = _skewt_std_logpdf_c(u, alpha, nu, log_c) - log_sig
            z0 = (mu + sigma * u - mu0) / sigma0
            lp_g = _skewt_std_logpdf_c(z0, alpha0, nu0, log_c0) - log_sig0
            return jac_f * (lp_f - lp_g)
        end
    end

    # Downside: (-∞, z_med]
    down = if z_med <= -M_cut
        _kl_tail(z_med, true)
    else
        t_left = (nu > 60.0 && log_c - 0.5 * (nu + 1.0) * log1p(M_cut * M_cut / nu) < -38.0) ?
                 0.0 : _kl_tail(-M_cut, true)
        c_left = 0.0
        cur = -M_cut
        for bp in (-3.0, 0.0, 3.0)
            if bp > cur && bp < z_med
                c_left += _gl_integrate(_kl_integrand, cur, bp, nodes, weights)
                cur = bp
            end
        end
        if cur < z_med
            c_left += _gl_integrate(_kl_integrand, cur, z_med, nodes, weights)
        end
        t_left + c_left
    end

    # Upside: [z_med, +∞)
    up = if z_med >= M_cut
        _kl_tail(z_med, false)
    else
        t_right = (nu > 60.0 && log_c - 0.5 * (nu + 1.0) * log1p(M_cut * M_cut / nu) < -38.0) ?
                  0.0 : _kl_tail(M_cut, false)
        c_right = 0.0
        cur = z_med
        for bp in (-3.0, 0.0, 3.0)
            if bp > cur && bp < M_cut
                c_right += _gl_integrate(_kl_integrand, cur, bp, nodes, weights)
                cur = bp
            end
        end
        if cur < M_cut
            c_right += _gl_integrate(_kl_integrand, cur, M_cut, nodes, weights)
        end
        c_right + t_right
    end
    return down, up
end

"""CRPS(F, y) = 2 ∫_0^1 ρ_u(y - Q(u)) du via split Gauss–Legendre quadrature at `p_y = F(y)`."""
function _skewt_crps(y::Float64, mu::Float64, sigma::Float64, alpha::Float64, nu::Float64;
                     p_y::Float64=NaN, fast_mode::Bool=false)
    z_y = (y - mu) / sigma
    py = isfinite(p_y) ? p_y : _skewt_std_cdf(z_y, alpha, nu; fast_mode=fast_mode)
    nodes = _GL_NODES_6
    weights = _GL_WEIGHTS_6
    tol_crps = fast_mode ? 1e-6 : 1e-7

    acc = 0.0
    if py > 1e-10
        # u = py * s^2 removes tail curvature at u -> 0+
        prev_z = NaN
        prev_u = NaN
        @inbounds for i in eachindex(nodes, weights)
            s = 0.5 * (nodes[i] + 1.0)
            u = clamp(py * s * s, 1e-9, 1.0 - 1e-9)
            qz = _skewt_std_quantile(u, alpha, nu; x0=prev_z, z_ref=prev_z, f_ref=prev_u,
                                     tol_q=tol_crps, fast_mode=fast_mode)
            prev_z = qz
            prev_u = u
            acc += (0.5 * weights[i]) * (2.0 * py * s) * u * (z_y - qz)
        end
    end
    if py < 1.0 - 1e-10
        # 1 - u = (1 - py) * s^2 removes tail curvature at u -> 1-
        q1m = 1.0 - py
        prev_z = NaN
        prev_u = NaN
        @inbounds for i in eachindex(nodes, weights)
            s = 0.5 * (nodes[i] + 1.0)
            one_minus_u = clamp(q1m * s * s, 1e-9, 1.0 - 1e-9)
            u = 1.0 - one_minus_u
            qz = _skewt_std_quantile(u, alpha, nu; x0=prev_z, z_ref=prev_z, f_ref=prev_u,
                                     tol_q=tol_crps, fast_mode=fast_mode)
            prev_z = qz
            prev_u = u
            acc += (0.5 * weights[i]) * (2.0 * q1m * s) * one_minus_u * (qz - z_y)
        end
    end
    return max(2.0 * sigma * acc, 0.0)
end

@inline function _skewt_four_std_quantiles(p1::Float64, p2::Float64, p3::Float64, p4::Float64,
                                           alp::Float64, nu::Float64;
                                           tol_q::Float64=1e-12, fast_mode::Bool=false)
    z1 = _skewt_std_quantile(p1, alp, nu; tol_q=tol_q, fast_mode=fast_mode)
    z2 = _skewt_std_quantile(p2, alp, nu; x0=z1 + 0.5, z_ref=z1, f_ref=p1, tol_q=tol_q, fast_mode=fast_mode)
    z3 = _skewt_std_quantile(p3, alp, nu; x0=z2 + 0.5, z_ref=z2, f_ref=p2, tol_q=tol_q, fast_mode=fast_mode)
    z4 = _skewt_std_quantile(p4, alp, nu; x0=z3 + 0.5, z_ref=z3, f_ref=p3, tol_q=tol_q, fast_mode=fast_mode)
    return (z1, z2, z3, z4)
end

# Lazy 2D lookup table of standardized quantiles at [0.05, 0.25, 0.75, 0.95] for fast global warm-starting
const _SKEWT_ANCHOR_PROBS = (0.05, 0.25, 0.75, 0.95)
const _SKEWT_TABLE_CACHE = Ref{Union{Nothing,Vector{NamedTuple{(:alpha,:nu,:z),Tuple{Float64,Float64,NTuple{4,Float64}}}}}}(nothing)

function _skewt_anchor_table()
    c = _SKEWT_TABLE_CACHE[]
    c === nothing || return c
    alphas = (-12.0, -7.0, -4.5, -3.0, -2.0, -1.4, -0.9, -0.5, -0.2, 0.0,
              0.2, 0.5, 0.9, 1.4, 2.0, 3.0, 4.5, 7.0, 12.0)
    nus = (2.2, 2.5, 3.0, 3.8, 5.0, 7.0, 10.0, 16.0, 35.0)
    entries = NamedTuple{(:alpha, :nu, :z),Tuple{Float64,Float64,NTuple{4,Float64}}}[]
    sizehint!(entries, length(alphas) * length(nus))
    p1, p2, p3, p4 = _SKEWT_ANCHOR_PROBS
    for a in alphas, nu in nus
        zs = _skewt_four_std_quantiles(p1, p2, p3, p4, a, nu)
        push!(entries, (alpha=a, nu=nu, z=zs))
    end
    _SKEWT_TABLE_CACHE[] = entries
    return entries
end

@inline function _skewt_ols_2d(qt::NTuple{4,Float64}, z::NTuple{4,Float64})
    mz = 0.25 * (z[1] + z[2] + z[3] + z[4])
    mq = 0.25 * (qt[1] + qt[2] + qt[3] + qt[4])
    szz = (z[1] - mz)^2 + (z[2] - mz)^2 + (z[3] - mz)^2 + (z[4] - mz)^2
    szz <= 1e-16 && return (mq, 1.0, Inf)
    szq = (z[1] - mz) * (qt[1] - mq) + (z[2] - mz) * (qt[2] - mq) +
          (z[3] - mz) * (qt[3] - mq) + (z[4] - mz) * (qt[4] - mq)
    sig = szq / szz
    sig <= 1e-8 && return (mq, 1.0, Inf)
    mu = mq - sig * mz
    sse = (qt[1] - (mu + sig * z[1]))^2 + (qt[2] - (mu + sig * z[2]))^2 +
          (qt[3] - (mu + sig * z[3]))^2 + (qt[4] - (mu + sig * z[4]))^2
    return (mu, sig, sse)
end

"""
Fit Azzalini–Capitanio (2003) skewed-t parameters `(μ, σ, α_skew, ν)` matching 4 anchor
quantiles `q_vals` at probability levels `p_vals` via Golub–Pereyra variable projection
with `Optim.LBFGS` + `Optim.NelderMead` refinement (`σ > 0`, `ν > 2.05`).
"""
function _skewt_fit_quantiles(q_vals::AbstractVector{<:Real},
                              p_vals::AbstractVector{<:Real};
                              warm_start::Union{Nothing,NTuple{4,Float64}}=nothing,
                              fast_mode::Bool=false)
    length(q_vals) == 4 || throw(ArgumentError("Expected 4 anchor quantiles, got $(length(q_vals))"))
    length(p_vals) == 4 || throw(ArgumentError("Expected 4 anchor probabilities, got $(length(p_vals))"))
    q1, q2, q3, q4 = Float64(q_vals[1]), Float64(q_vals[2]), Float64(q_vals[3]), Float64(q_vals[4])
    p1, p2, p3, p4 = Float64(p_vals[1]), Float64(p_vals[2]), Float64(p_vals[3]), Float64(p_vals[4])

    m0 = 0.5 * (q2 + q3)
    iqr = q3 - q2
    spread = q4 - q1
    s0 = max(iqr / 1.3489795003921634, spread / 3.289707)
    if !isfinite(s0) || s0 <= 1e-10 || q4 <= q1
        return (m0, max(isfinite(s0) ? s0 : 1.0, 1e-6), 0.0, 10.0)
    end
    qt = ((q1 - m0) / s0, (q2 - m0) / s0, (q3 - m0) / s0, (q4 - m0) / s0)

    best_alp = 0.0
    best_nu = 6.0
    best_sse = Inf

    near_std_anchors = max(abs(p1 - 0.05), abs(p2 - 0.25), abs(p3 - 0.75), abs(p4 - 0.95)) <= 0.02
    if near_std_anchors
        for entry in _skewt_anchor_table()
            _, _, sse_e = _skewt_ols_2d(qt, entry.z)
            if sse_e < best_sse
                best_sse = sse_e
                best_alp = entry.alpha
                best_nu = entry.nu
            end
        end
    else
        for a in (-3.0, -1.0, 0.0, 1.0, 3.0), nu in (3.0, 6.0, 15.0)
            z_e = _skewt_four_std_quantiles(p1, p2, p3, p4, a, nu)
            _, _, sse_e = _skewt_ols_2d(qt, z_e)
            if sse_e < best_sse
                best_sse = sse_e
                best_alp = a
                best_nu = nu
            end
        end
    end

    tol_init = fast_mode ? 1e-8 : 1e-12
    if warm_start !== nothing
        _, w_sig, w_alp, w_nu = warm_start
        if isfinite(w_sig) && w_sig > 1e-8 && isfinite(w_nu) && w_nu > 2.055 && abs(w_alp) <= 25.0
            z_w = _skewt_four_std_quantiles(p1, p2, p3, p4, w_alp, w_nu; tol_q=tol_init, fast_mode=fast_mode)
            _, _, sse_w = _skewt_ols_2d(qt, z_w)
            if sse_w < best_sse
                best_sse = sse_w
                best_alp = w_alp
                best_nu = w_nu
            end
        end
    end

    # 2D variable projection on shape parameters θ = [α, log(ν - 2.05)] with exact OLS (μ, σ)
    θ0 = Float64[
        clamp(best_alp, -20.0, 20.0),
        log(clamp(best_nu - 2.05, 1e-3, 180.0)),
    ]

    tol_q = fast_mode ? 1e-8 : 1e-12
    function _obj_shape(θ::AbstractVector{Float64})
        alp_c = θ[1]
        lnu = θ[2]
        alp_cl = clamp(alp_c, -25.0, 25.0)
        nu_c = 2.05 + exp(clamp(lnu, -12.0, 5.5))
        zs = _skewt_four_std_quantiles(p1, p2, p3, p4, alp_cl, nu_c; tol_q=tol_q, fast_mode=fast_mode)
        _, _, sse = _skewt_ols_2d(qt, zs)
        pen = 0.0
        if abs(alp_c) > 25.0
            pen += (abs(alp_c) - 25.0)^2
        end
        if lnu < -12.0
            pen += (-12.0 - lnu)^2
        elseif lnu > 5.5
            pen += (lnu - 5.5)^2
        end
        return sse + pen
    end

    θ_opt = if fast_mode && best_sse <= 1e-4
        θ0
    else
        lbfgs_iters = fast_mode ? 2 : 100
        lbfgs_gtol = fast_mode ? 1e-3 : 1e-10
        nm_iters = fast_mode ? 8 : 300
        nm_gtol = fast_mode ? 1e-3 : 1e-11
        opts_lbfgs = fast_mode ?
            Optim.Options(iterations=lbfgs_iters, g_tol=lbfgs_gtol, f_reltol=1e-4, x_abstol=1e-3, show_trace=false) :
            Optim.Options(iterations=lbfgs_iters, g_tol=lbfgs_gtol, show_trace=false)

        res_lbfgs = Optim.optimize(_obj_shape, θ0, Optim.LBFGS(), opts_lbfgs)
        θ_mid = Optim.minimizer(res_lbfgs)
        f_mid = Optim.minimum(res_lbfgs)

        nm_thresh = fast_mode ? 5e-4 : 1e-18
        if f_mid > nm_thresh
            opts_nm = fast_mode ?
                Optim.Options(iterations=nm_iters, g_tol=nm_gtol, f_reltol=1e-4, show_trace=false) :
                Optim.Options(iterations=nm_iters, g_tol=nm_gtol, show_trace=false)
            res_nm = Optim.optimize(_obj_shape, θ_mid, Optim.NelderMead(), opts_nm)
            θ_best, f_best = Optim.minimum(res_nm) <= f_mid ? (Optim.minimizer(res_nm), Optim.minimum(res_nm)) : (θ_mid, f_mid)
            f_best <= best_sse ? θ_best : θ0
        else
            f_mid <= best_sse ? θ_mid : θ0
        end
    end

    alp_hat = clamp(θ_opt[1], -25.0, 25.0)
    nu_hat = 2.05 + exp(clamp(θ_opt[2], -12.0, 5.5))
    zs_opt = _skewt_four_std_quantiles(p1, p2, p3, p4, alp_hat, nu_hat;
                                       tol_q=(fast_mode ? 1e-8 : 1e-12), fast_mode=fast_mode)
    mu_t, sig_t, _ = _skewt_ols_2d(qt, zs_opt)
    if !isfinite(sig_t) || sig_t <= 1e-8
        mu_t = 0.0
        sig_t = 1.0
    end
    mu_hat = m0 + s0 * mu_t
    sig_hat = s0 * sig_t
    return (mu_hat, sig_hat, alp_hat, nu_hat)
end

"""Select 4 distinct anchor indices in `taus` nearest to `(0.05, 0.25, 0.75, 0.95)`."""
function _gar_select_anchors(taus::AbstractVector{T}) where {T<:AbstractFloat}
    M = length(taus)
    M >= 4 || throw(ArgumentError("density=:skewed_t requires at least 4 quantiles in taus, got $M"))
    perm = sortperm(taus)
    if M == 4
        return (perm[1], perm[2], perm[3], perm[4]),
               T[taus[perm[1]], taus[perm[2]], taus[perm[3]], taus[perm[4]]]
    end
    targets = (0.05, 0.25, 0.75, 0.95)
    best_cost = Inf
    best_idx = (1, 2, 3, 4)
    @inbounds for i1 in 1:(M - 3)
        c1 = abs(Float64(taus[perm[i1]]) - targets[1])
        c1 >= best_cost && continue
        for i2 in (i1 + 1):(M - 2)
            c2 = c1 + abs(Float64(taus[perm[i2]]) - targets[2])
            c2 >= best_cost && continue
            for i3 in (i2 + 1):(M - 1)
                c3 = c2 + abs(Float64(taus[perm[i3]]) - targets[3])
                c3 >= best_cost && continue
                for i4 in (i3 + 1):M
                    c4 = c3 + abs(Float64(taus[perm[i4]]) - targets[4])
                    if c4 < best_cost
                        best_cost = c4
                        best_idx = (perm[i1], perm[i2], perm[i3], perm[i4])
                    end
                end
            end
        end
    end
    p_anchors = T[taus[best_idx[1]], taus[best_idx[2]], taus[best_idx[3]], taus[best_idx[4]]]
    return best_idx, p_anchors
end

