"""Build design matrix `Z` (`T_eff × (1 + r_j + lags)`) and origin vector `z_oos` for quantile `j`."""
function _gar_build_design(F::Matrix{T}, y::Vector{T}, t_start::Int, t_end::Int,
                           lags::Int) where {T<:AbstractFloat}
    T_obs, r = size(F)
    T_eff = t_end - t_start + 1
    k = 1 + r + lags
    Z = Matrix{T}(undef, T_eff, k)
    @inbounds for (row, t) in enumerate(t_start:t_end)
        Z[row, 1] = one(T)
        for f in 1:r
            Z[row, 1 + f] = F[t, f]
        end
        for l in 1:lags
            Z[row, 1 + r + l] = y[t - l + 1]
        end
    end
    z_oos = Vector{T}(undef, k)
    @inbounds begin
        z_oos[1] = one(T)
        for f in 1:r
            z_oos[1 + f] = F[T_obs, f]
        end
        for l in 1:lags
            z_oos[1 + r + l] = y[T_obs - l + 1]
        end
    end
    return Z, z_oos
end

"""Solve direct `h`-step quantile regression at `tau` with ridge fallback if sample is small/singular."""
function _gar_solve_qr!(beta::Vector{T}, Z::AbstractMatrix{T},
                        y_target::AbstractVector{T}, tau::T,
                        ws::Union{Nothing,_QRegWorkspace{T}}) where {T<:AbstractFloat}
    n, k = size(Z)
    if n > k + 1
        ws_use = ws === nothing ? _QRegWorkspace{T}(n, k) : ws
        tol_ipm = max(T(1e-8), T(100) * eps(T))
        _, conv = _qreg_ipm!(beta, Z, y_target, tau, ws_use; tol=tol_ipm, maxit=60)
        if all(isfinite, beta) && (conv || sum(abs, beta) <= T(1e6))
            return beta
        end
    end
    if n >= 2
        beta .= _qfm_ridge_solve(Z, y_target, T(1e-3))
        if all(isfinite, beta)
            return beta
        end
    end
    fill!(beta, zero(T))
    beta[1] = T(Statistics.quantile(y_target, tau))
    return beta
end

"""Rearrange each row of `Q` across quantile columns in ascending `taus` order (`perm = sortperm(taus)`)."""
function _gar_rearrange_rows!(Q::Matrix{T}, perm::Vector{Int}) where {T<:AbstractFloat}
    T_eff, M = size(Q)
    M <= 1 && return Q
    buf = Vector{T}(undef, M)
    @inbounds for t in 1:T_eff
        for j in 1:M
            buf[j] = Q[t, perm[j]]
        end
        sort!(buf)
        for j in 1:M
            Q[t, perm[j]] = buf[j]
        end
    end
    return Q
end

function _gar_rearrange_vec!(v::Vector{T}, perm::Vector{Int}) where {T<:AbstractFloat}
    M = length(v)
    M <= 1 && return v
    buf = Vector{T}(undef, M)
    @inbounds for j in 1:M
        buf[j] = v[perm[j]]
    end
    sort!(buf)
    @inbounds for j in 1:M
        v[perm[j]] = buf[j]
    end
    return v
end

"""Evaluate density fit, GaR, ES, entropies, and CRPS for a single quantile vector `q_row`."""
function _gar_eval_density_point(q_row::AbstractVector{T}, taus::Vector{T}, perm::Vector{Int},
                                 y_real::Union{Nothing,Float64},
                                 alpha::Float64, density::Symbol,
                                 anchor_idx::NTuple{4,Int}, anchor_probs::Vector{T},
                                 uncond_params::Tuple;
                                 warm_start::Union{Nothing,NTuple{4,Float64}}=nothing,
                                 fast_mode::Bool=false) where {T<:AbstractFloat}
    taus_s = @view taus[perm]
    q_s = T[q_row[idx] for idx in perm]

    if density === :skewed_t
        q_anc = Float64[q_row[anchor_idx[1]], q_row[anchor_idx[2]],
                        q_row[anchor_idx[3]], q_row[anchor_idx[4]]]
        params = _skewt_fit_quantiles(q_anc, anchor_probs;
                                      warm_start=warm_start, fast_mode=fast_mode)
        mu, sig, alp, nu = params
        z_a = _skewt_std_quantile(alpha, alp, nu;
                                  tol_q=(fast_mode ? 1e-8 : 1e-12), fast_mode=fast_mode)
        gar_v = mu + sig * z_a
        es_v = _skewt_es(alpha, mu, sig, alp, nu; z_alpha=z_a, fast_mode=fast_mode)
        dn_v, up_v = _skewt_entropy(mu, sig, alp, nu, uncond_params...; fast_mode=fast_mode)
        pit_v = y_real === nothing ? NaN : _skewt_cdf(y_real, mu, sig, alp, nu; fast_mode=fast_mode)
        crps_v = y_real === nothing ? NaN : _skewt_crps(y_real, mu, sig, alp, nu; p_y=pit_v, fast_mode=fast_mode)
        return (params=collect(params), raw_tuple=params, gar=gar_v, es=es_v,
                up=up_v, down=dn_v, pit=pit_v, crps=crps_v)
    elseif density === :normal
        mu, sig = _normal_fit_quantiles(q_s, taus_s)
        gar_v = mu + sig * Distributions.quantile(Distributions.Normal(), alpha)
        es_v = _normal_es(alpha, mu, sig)
        dn_v, up_v = _normal_entropy(mu, sig, uncond_params[1], uncond_params[2])
        pit_v = y_real === nothing ? NaN : Distributions.cdf(Distributions.Normal(mu, sig), y_real)
        crps_v = y_real === nothing ? NaN : _normal_crps(y_real, mu, sig)
        return (params=Float64[mu, sig], raw_tuple=(mu, sig, 0.0, Inf), gar=gar_v, es=es_v,
                up=up_v, down=dn_v, pit=pit_v, crps=crps_v)
    else
        gar_v = _empirical_quantile(taus_s, q_s, alpha)
        es_v = _empirical_es(taus_s, q_s, alpha)
        pit_v = y_real === nothing ? NaN : _empirical_cdf(taus_s, q_s, y_real)
        crps_v = y_real === nothing ? NaN : _empirical_crps(taus_s, q_s, y_real)
        return (params=Float64[], raw_tuple=(), gar=gar_v, es=es_v,
                up=NaN, down=NaN, pit=pit_v, crps=crps_v)
    end
end

"""Resolve target series `(y, target_name)` from column index, name, or vector."""
function _gar_resolve_target(X::AbstractMatrix{T}, target_col::Union{Int,AbstractString,Symbol,AbstractVector{<:Real}},
                             varnames::Union{Nothing,AbstractVector{<:AbstractString}}) where {T<:AbstractFloat}
    T_obs, N = size(X)
    if target_col isa Int
        (1 <= target_col <= N) || throw(ArgumentError(
            "target_col index $target_col out of bounds for matrix with $N columns"))
        vn = varnames === nothing ? "Var $target_col" : String(varnames[target_col])
        return Vector{T}(@view(X[:, target_col])), vn
    elseif target_col isa AbstractString || target_col isa Symbol
        nm = String(target_col)
        varnames === nothing && throw(ArgumentError(
            "varnames must be provided when specifying target_col='$nm' by name"))
        idx = findfirst(==(nm), varnames)
        idx === nothing && throw(ArgumentError(
            "Target variable '$nm' not found in varnames: $(collect(varnames))"))
        return Vector{T}(@view(X[:, idx])), nm
    else
        length(target_col) == T_obs || throw(ArgumentError(
            "target vector has length $(length(target_col)) but X has $T_obs rows"))
        _validate_data(target_col, "y")
        return Vector{T}(target_col), "y"
    end
end

"""Core Growth-at-Risk estimation given factor matrices `F_list`, target `y`, and `taus`."""
function _gar_core(F_list::Vector{Matrix{T}}, y::Vector{T}, target_name::String,
                   taus::Vector{T}, h::Int, lags::Int, rearrange::Bool,
                   alpha_T::T, density::Symbol, oos_split::Union{Nothing,Int},
                   seed::Union{Integer,Nothing}, settings::Dict{String,Any}) where {T<:AbstractFloat}
    T_obs = length(y)
    M = length(taus)
    validate_option(density, "density", (:skewed_t, :normal, :none))
    h >= 1 || throw(ArgumentError("forecast horizon h must be >= 1, got $h"))
    lags >= 0 || throw(ArgumentError("lags must be >= 0, got $lags"))
    (isfinite(alpha_T) && zero(T) < alpha_T < one(T)) ||
        throw(ArgumentError("alpha must lie strictly in (0, 1), got $alpha_T"))
    M >= 1 || throw(ArgumentError("taus must not be empty"))
    for (j, tj) in enumerate(taus)
        (isfinite(tj) && zero(T) < tj < one(T)) ||
            throw(ArgumentError("every tau must lie strictly in (0, 1), got $tj at index $j"))
    end
    allunique(round.(Float64.(taus); digits=12)) ||
        throw(ArgumentError("taus must contain distinct quantile levels"))
    if density === :skewed_t && M < 4
        throw(ArgumentError("density=:skewed_t requires at least 4 quantile levels in taus, got $M"))
    elseif density === :normal && M < 2
        throw(ArgumentError("density=:normal requires at least 2 quantile levels in taus, got $M"))
    end

    t_start = max(lags, 1)
    t_end = T_obs - h
    T_eff = t_end - t_start + 1
    T_eff >= 2 || throw(ArgumentError(
        "Not enough observations (T=$T_obs) for horizon h=$h and lags=$lags"))

    max_k = 1 + maximum(size(Fj, 2) for Fj in F_list) + lags
    if oos_split !== nothing
        min_split = t_start + h + max_k
        (min_split <= oos_split <= t_end) || throw(ArgumentError(
            "oos_split must lie in [$min_split, $t_end] for T=$T_obs, h=$h, lags=$lags; got $oos_split"))
    end

    y_eff = Vector{T}(@view(y[(t_start + h):T_obs]))
    perm = sortperm(taus)

    # 1. Direct h-step quantile regressions per quantile
    fitted_quantiles = Matrix{T}(undef, T_eff, M)
    oos_quantiles = Vector{T}(undef, M)
    coefficients = Vector{Vector{T}}(undef, M)
    designs = Vector{Matrix{T}}(undef, M)
    oos_vecs = Vector{Vector{T}}(undef, M)

    for j in 1:M
        Fj = F_list[j]
        size(Fj, 1) == T_obs || throw(DimensionMismatch(
            "Factor matrix at quantile index $j has $(size(Fj, 1)) rows, expected $T_obs"))
        Zj, z_oos_j = _gar_build_design(Fj, y, t_start, t_end, lags)
        designs[j] = Zj
        oos_vecs[j] = z_oos_j
        kj = size(Zj, 2)
        bj = Vector{T}(undef, kj)
        _gar_solve_qr!(bj, Zj, y_eff, taus[j], nothing)
        coefficients[j] = bj
        fitted_quantiles[:, j] .= Zj * bj
        oos_quantiles[j] = dot(z_oos_j, bj)
    end

    if rearrange && M > 1
        _gar_rearrange_rows!(fitted_quantiles, perm)
        _gar_rearrange_vec!(oos_quantiles, perm)
    end

    # Quantile scores (in-sample mean check loss per tau)
    quantile_score = Vector{T}(undef, M)
    resid_buf = Vector{T}(undef, T_eff)
    @inbounds for j in 1:M
        for t in 1:T_eff
            resid_buf[t] = y_eff[t] - fitted_quantiles[t, j]
        end
        quantile_score[j] = _check_loss(resid_buf, taus[j]) / T(T_eff)
    end

    # 2. Unconditional benchmark density for relative entropy + anchor setup
    anchor_idx, anchor_probs = density === :skewed_t ? _gar_select_anchors(taus) : ((1, 1, 1, 1), T[])
    uncond_params = if density === :skewed_t
        q_unc = Float64[Statistics.quantile(y_eff, Float64(p)) for p in anchor_probs]
        _skewt_fit_quantiles(q_unc, anchor_probs; fast_mode=false)
    elseif density === :normal
        (Float64(Statistics.mean(y_eff)), max(Float64(Statistics.std(y_eff)), 1e-6))
    else
        ()
    end

    # 3. Fit density and compute GaR, ES, entropies, CRPS (in-sample + T+h)
    n_par = density === :skewed_t ? 4 : (density === :normal ? 2 : 0)
    density_params = n_par > 0 ? Matrix{T}(undef, T_eff, n_par) : Matrix{T}(undef, 0, 0)
    gar = Vector{T}(undef, T_eff)
    expected_shortfall = Vector{T}(undef, T_eff)
    upside_entropy = Vector{T}(undef, T_eff)
    downside_entropy = Vector{T}(undef, T_eff)
    crps = Vector{T}(undef, T_eff)

    alpha_f = Float64(alpha_T)
    warm_st = nothing
    for t in 1:T_eff
        res_t = _gar_eval_density_point(
            @view(fitted_quantiles[t, :]), taus, perm, Float64(y_eff[t]),
            alpha_f, density, anchor_idx, anchor_probs, uncond_params;
            warm_start=warm_st, fast_mode=(t > 1),
        )
        if n_par > 0
            density_params[t, :] .= T.(res_t.params)
            if density === :skewed_t
                warm_st = res_t.raw_tuple
            end
        end
        gar[t] = T(res_t.gar)
        expected_shortfall[t] = T(res_t.es)
        upside_entropy[t] = T(res_t.up)
        downside_entropy[t] = T(res_t.down)
        crps[t] = T(res_t.crps)
    end

    res_oos = _gar_eval_density_point(
        oos_quantiles, taus, perm, nothing,
        alpha_f, density, anchor_idx, anchor_probs, uncond_params;
        warm_start=warm_st, fast_mode=false,
    )
    oos_density_params = n_par > 0 ? T.(res_oos.params) : T[]
    oos_gar = T(res_oos.gar)
    oos_expected_shortfall = T(res_oos.es)
    oos_upside_entropy = T(res_oos.up)
    oos_downside_entropy = T(res_oos.down)

    # 4. Optional expanding-window out-of-sample evaluation
    if oos_split === nothing
        pit = T[]
        oos_quantile_scores = T[]
        oos_crps = T[]
    else
        oos_origins = oos_split:t_end
        n_oos = length(oos_origins)
        pit = Vector{T}(undef, n_oos)
        oos_crps = Vector{T}(undef, n_oos)
        qs_accum = zeros(Float64, M)
        q_oos_row = Vector{T}(undef, M)
        b_oos = [Vector{T}(undef, size(designs[j], 2)) for j in 1:M]
        z_orig = Vector{T}(undef, maximum(size(designs[j], 2) for j in 1:M))

        for (idx_o, t_orig) in enumerate(oos_origins)
            train_end_t = t_orig - h
            n_train = train_end_t - t_start + 1
            y_tr = @view y_eff[1:n_train]
            orig_row = t_orig - t_start + 1

            for j in 1:M
                Zj_tr = @view designs[j][1:n_train, :]
                _gar_solve_qr!(b_oos[j], Zj_tr, y_tr, taus[j], nothing)
                kj = size(Zj_tr, 2)
                @inbounds for c in 1:kj
                    z_orig[c] = designs[j][orig_row, c]
                end
                q_oos_row[j] = dot(@view(z_orig[1:kj]), b_oos[j])
            end
            if rearrange && M > 1
                _gar_rearrange_vec!(q_oos_row, perm)
            end

            y_real_t = Float64(y[t_orig + h])
            @inbounds for j in 1:M
                u = y_real_t - Float64(q_oos_row[j])
                tau_f = Float64(taus[j])
                qs_accum[j] += u * (tau_f - (u < 0.0 ? 1.0 : 0.0))
            end

            eval_o = _gar_eval_density_point(
                q_oos_row, taus, perm, y_real_t,
                alpha_f, density, anchor_idx, anchor_probs, uncond_params;
                warm_start=warm_st, fast_mode=true,
            )
            pit[idx_o] = T(eval_o.pit)
            oos_crps[idx_o] = T(eval_o.crps)
        end
        oos_quantile_scores = T.(qs_accum ./ n_oos)
    end

    mani = seed === nothing ? nothing : capture_manifest(; seed=seed, settings=settings)

    return GrowthAtRiskResult{T}(
        y, target_name, taus, h, lags, alpha_T, density, rearrange,
        fitted_quantiles, y_eff, oos_quantiles, coefficients,
        density_params, oos_density_params, gar, expected_shortfall,
        upside_entropy, downside_entropy, oos_gar, oos_expected_shortfall,
        oos_upside_entropy, oos_downside_entropy, quantile_score, crps,
        oos_split, pit, oos_quantile_scores, oos_crps, T_obs, T_eff, mani,
    )
end

"""
    growth_at_risk(grid::QuantileFactorGrid{T}, y_or_col, h::Int=1;
                   X=nothing, taus=nothing, lags::Int=1, rearrange::Bool=true,
                   alpha::Real=0.05, density::Symbol=:skewed_t,
                   oos_split::Union{Nothing,Int}=nothing,
                   rng::AbstractRNG=Random.default_rng(),
                   seed::Union{Integer,Nothing}=nothing) -> GrowthAtRiskResult{T}

    growth_at_risk(X::AbstractMatrix{<:Real}, target_col, h::Int=1;
                   r::Union{Int,Symbol}=2,
                   taus::AbstractVector{<:Real}=[0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95],
                   lags::Int=1, rearrange::Bool=true, alpha::Real=0.05,
                   density::Symbol=:skewed_t, standardize::Bool=true,
                   oos_split::Union{Nothing,Int}=nothing,
                   varnames::Union{Nothing,AbstractVector{<:AbstractString}}=nothing,
                   rng::AbstractRNG=Random.default_rng(),
                   seed::Union{Integer,Nothing}=nothing) -> GrowthAtRiskResult

Estimate Growth-at-Risk (Adrian, Boyarchenko & Giannone 2019) using quantile factors
from a [`QuantileFactorGrid`](@ref) or directly from a data panel `X`.

```math
Q_{y_{t+h}}(\\tau \\mid I_t) = \\alpha_h(\\tau) + \\beta_h(\\tau)' \\hat{F}_t(\\tau) + \\gamma_h(\\tau)' y_{t:-1:t-p+1},
\\qquad
f(y; \\mu, \\sigma, \\alpha_s, \\nu) = \\frac{2}{\\sigma}\\, t_{\\nu}(z)\\, T_{\\nu+1}\\!\\left(\\alpha_s z \\sqrt{\\frac{\\nu+1}{\\nu + z^2}}\\right)
```

where:
- ``y_{t+h}`` is the ``h``-step-ahead target variable (`target_col` / `y_or_col`)
- ``\\hat{F}_t(\\tau)`` are the estimated quantile factors at quantile ``\\tau``
- ``y_{t:-1:t-p+1}`` are the ``p`` lagged target values (`p = lags`)
- ``z = (y - \\mu) / \\sigma`` is the standardized outcome under the Azzalini–Capitanio (2003) skewed-``t`` density with location ``\\mu``, scale ``\\sigma > 0``, skewness ``\\alpha_s``, and degrees of freedom ``\\nu > 2.05``
- ``t_\\nu(\\cdot)`` and ``T_{\\nu+1}(\\cdot)`` denote the standard Student-``t`` PDF and CDF

# Arguments
- `grid::QuantileFactorGrid{T}` — pre-estimated multi-quantile factor grid
- `X::AbstractMatrix{<:Real}` — raw data panel (`T_obs × N`)
- `y_or_col` / `target_col` — column index (`Int`), variable name (`AbstractString` or `Symbol`), or external target vector (`AbstractVector{<:Real}`)
- `h::Int = 1` — forecast horizon (`>= 1`)

# Keyword Arguments
- `r::Union{Int,Symbol} = 2` — quantile factor count or `:auto` (matrix method only)
- `taus` — quantile grid strictly in `(0, 1)` (defaults to `grid.taus` for `QuantileFactorGrid` and `[0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95]` for `X`)
- `lags::Int = 1` — number of lags of `y` included in direct quantile regressions (`>= 0`)
- `rearrange::Bool = true` — apply Chernozhukov–Fernández-Val–Galichon (2010) monotone rearrangement across `taus`
- `alpha::Real = 0.05` — tail probability level strictly in `(0, 1)` for `GaR_α` and `ES_α`
- `density::Symbol = :skewed_t` — predictive density fit (`:skewed_t`, `:normal`, or `:none`)
- `standardize::Bool = true` — standardize `X` before QFM estimation (matrix method only)
- `oos_split::Union{Nothing,Int} = nothing` — origin index starting expanding-window out-of-sample evaluation (computes `pit`, `oos_quantile_scores`, `oos_crps`)
- `varnames::Union{Nothing,AbstractVector{<:AbstractString}} = nothing` — panel variable names (matrix method)
- `rng::AbstractRNG = Random.default_rng()` — RNG passed to QFM estimation
- `seed::Union{Integer,Nothing} = nothing` — integer seed recorded in `manifest` when provided

# Returns
A [`GrowthAtRiskResult`](@ref) containing conditional quantiles, `gar`, `expected_shortfall`,
`upside_entropy`, `downside_entropy`, `quantile_score`, `crps`, optional OOS evaluation
vectors (`pit`, `oos_quantile_scores`, `oos_crps`), and reproducibility metadata.

# References
- Adrian, T., Boyarchenko, N., & Giannone, D. (2019). Vulnerable growth.
  *American Economic Review*, 109(4), 1263–1289.
- Azzalini, A., & Capitanio, A. (2003). Distributions generated by perturbation of
  symmetry with emphasis on a multivariate skew t-distribution. *JRSS-B*, 65(2), 367–389.
- Chernozhukov, V., Fernández-Val, I., & Galichon, A. (2010). Quantile and probability
  curves without crossing. *Econometrica*, 78(3), 1093–1125.
"""
function growth_at_risk(grid::QuantileFactorGrid{T},
                        y_or_col::Union{Int,AbstractString,Symbol,AbstractVector{<:Real}},
                        h::Int=1;
                        X::Union{Nothing,AbstractMatrix}=nothing,
                        taus=nothing,
                        lags::Int=1,
                        rearrange::Bool=true,
                        alpha::Real=0.05,
                        density::Symbol=:skewed_t,
                        oos_split::Union{Nothing,Int}=nothing,
                        rng::AbstractRNG=Random.default_rng(),
                        seed::Union{Integer,Nothing}=nothing) where {T<:AbstractFloat}
    isempty(grid.models) && throw(ArgumentError("QuantileFactorGrid must not be empty"))
    _ = _resolve_repro_rng(rng, seed)

    X_src = if X === nothing
        grid.models[1].X
    else
        _validate_data(X, "X")
        Matrix{T}(X)
    end
    T_fac = size(grid.models[1].factors, 1)
    size(X_src, 1) == T_fac || throw(DimensionMismatch(
        "X has $(size(X_src, 1)) rows but grid factors have $T_fac rows"))

    y, target_name = _gar_resolve_target(X_src, y_or_col, grid.varnames)

    taus_T = if taus === nothing
        copy(grid.taus)
    else
        !isempty(taus) || throw(ArgumentError("taus must not be empty"))
        T[T(tj) for tj in taus]
    end

    M = length(taus_T)
    F_list = Vector{Matrix{T}}(undef, M)
    for j in 1:M
        tj = Float64(taus_T[j])
        best_idx = argmin(k -> abs(Float64(grid.taus[k]) - tj), 1:length(grid.models))
        F_list[j] = grid.models[best_idx].factors
    end

    settings = Dict{String,Any}(
        "target" => target_name,
        "h" => h,
        "lags" => lags,
        "taus" => Float64.(taus_T),
        "rearrange" => rearrange,
        "alpha" => Float64(alpha),
        "density" => String(density),
        "oos_split" => oos_split,
    )
    return _gar_core(F_list, y, target_name, taus_T, h, lags, rearrange,
                     T(alpha), density, oos_split, seed, settings)
end

function growth_at_risk(X::AbstractMatrix{<:Real},
                        target_col::Union{Int,AbstractString,Symbol,AbstractVector{<:Real}},
                        h::Int=1;
                        r::Union{Int,Symbol}=2,
                        taus::AbstractVector{<:Real}=[0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95],
                        lags::Int=1,
                        rearrange::Bool=true,
                        alpha::Real=0.05,
                        density::Symbol=:skewed_t,
                        standardize::Bool=true,
                        oos_split::Union{Nothing,Int}=nothing,
                        varnames::Union{Nothing,AbstractVector{<:AbstractString}}=nothing,
                        rng::AbstractRNG=Random.default_rng(),
                        seed::Union{Integer,Nothing}=nothing)
    _validate_data(X, "X")
    FP = target_col isa AbstractVector ? float(promote_type(eltype(X), eltype(target_col))) : float(eltype(X))
    X_mat = Matrix{FP}(X)
    T_obs, N = size(X_mat)

    vnames = varnames === nothing ? nothing : String.(collect(varnames))
    if vnames !== nothing
        length(vnames) == N || throw(ArgumentError(
            "varnames has $(length(vnames)) entries but X has $N columns"))
    end
    y, target_name = _gar_resolve_target(X_mat, target_col, vnames)

    # Validate arguments before running potentially expensive QFM grid fit
    h >= 1 || throw(ArgumentError("forecast horizon h must be >= 1, got $h"))
    lags >= 0 || throw(ArgumentError("lags must be >= 0, got $lags"))
    validate_option(density, "density", (:skewed_t, :normal, :none))
    alpha_T = FP(alpha)
    (isfinite(alpha) && zero(FP) < alpha_T < one(FP)) ||
        throw(ArgumentError("alpha must lie strictly in (0, 1), got $alpha"))
    !isempty(taus) || throw(ArgumentError("taus must not be empty"))
    taus_T = FP[FP(tj) for tj in taus]
    for (j, tj) in enumerate(taus_T)
        (isfinite(tj) && zero(FP) < tj < one(FP)) ||
            throw(ArgumentError("every tau must lie strictly in (0, 1), got $tj at index $j"))
    end
    allunique(round.(Float64.(taus_T); digits=12)) ||
        throw(ArgumentError("taus must contain distinct quantile levels"))
    if density === :skewed_t && length(taus_T) < 4
        throw(ArgumentError("density=:skewed_t requires at least 4 quantile levels in taus, got $(length(taus_T))"))
    elseif density === :normal && length(taus_T) < 2
        throw(ArgumentError("density=:normal requires at least 2 quantile levels in taus, got $(length(taus_T))"))
    end
    t_start = max(lags, 1)
    (T_obs - h) - t_start + 1 >= 2 || throw(ArgumentError(
        "Not enough observations (T=$T_obs) for horizon h=$h and lags=$lags"))

    rng_use = _resolve_repro_rng(rng, seed)
    grid_seed = rand(rng_use, UInt64)
    vn_grid = vnames === nothing ? ["Var $i" for i in 1:N] : vnames
    grid = estimate_qfm(X_mat, r, taus_T; standardize=standardize,
                        varnames=vn_grid, rng=Random.Xoshiro(grid_seed), seed=nothing)

    F_list = Matrix{FP}[m.factors for m in grid.models]
    settings = Dict{String,Any}(
        "target" => target_name,
        "h" => h,
        "r" => r isa Symbol ? String(r) : r,
        "lags" => lags,
        "taus" => Float64.(taus_T),
        "rearrange" => rearrange,
        "alpha" => Float64(alpha_T),
        "density" => String(density),
        "standardize" => standardize,
        "oos_split" => oos_split,
    )
    return _gar_core(F_list, y, target_name, taus_T, h, lags, rearrange,
                     alpha_T, density, oos_split, seed, settings)
end

