@inline function _gl_integrate(f, a::Float64, b::Float64,
                               nodes::Vector{Float64}, weights::Vector{Float64})
    b <= a && return 0.0
    half = 0.5 * (b - a)
    mid = 0.5 * (a + b)
    acc = 0.0
    @inbounds for i in eachindex(nodes, weights)
        acc += weights[i] * f(mid + half * nodes[i])
    end
    return half * acc
end

